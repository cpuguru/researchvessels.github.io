#!/usr/bin/env python3
"""Refresh data/uncrewed_deployments.json and data/uncrewed_deployments.js (the checked-in snapshot behind the map's
"Active uncrewed deployments" layer). Run by hand from the repo root: python3 tools/refresh_uncrewed_deployments.py
It only writes those two files. Review the diff, then commit and push yourself; nothing here publishes anything.

Sources (public, no keys):
 - IOOS Glider DAC ERDDAP (https://gliders.ioos.us/erddap/): datasets whose latest data time is within the last 3 days;
   latest position of each from tabledap orderByMax("time"). The page also fetches this live; the snapshot is the fallback.
 - Argo floats from the Ifremer Argo ERDDAP (https://erddap.ifremer.fr/erddap/tabledap/ArgoFloats): latest profile position of each
   float with a profile in the last 12 days. This server sends no CORS header, so browsers cannot read it directly; hence the snapshot.
Positions are rounded to 0.01 degrees (about 1 km), which is plenty for a world map and keeps the file small."""
import json, sys, time, urllib.request, urllib.parse, datetime, re
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
UA = 'researchvessels.org snapshot script (contact ships@oceandata.org)'
GLIDER_DAYS, ARGO_DAYS = 3, 12
def get(url, tries=3):
    for i in range(tries):
        try:
            req = urllib.request.Request(url, headers={'User-Agent': UA})
            return json.loads(urllib.request.urlopen(req, timeout=120).read().decode('utf-8'))
        except Exception as e:
            err = e; time.sleep(3)
    raise SystemExit(f'fetch failed: {url}: {err}')
def rows(j): return j['table']['rows']
now = datetime.datetime.now(datetime.timezone.utc)
base = 'https://gliders.ioos.us/erddap/tabledap/'
q = 'allDatasets.json?datasetID,title,institution,minTime,maxTime&maxTime%3E=now-' + str(GLIDER_DAYS) + 'days'
gl = []
for did, title, inst, t0, t1 in rows(get(base + q)):
    last = rows(get(base + urllib.parse.quote(did) + '.json?time,latitude,longitude&orderByMax(%22time%22)'))
    if not last or last[0][1] is None or last[0][2] is None: continue
    t, lat, lon = last[0]
    gl.append({'id': did, 'title': title, 'institution': inst, 'start': t0, 'time': t, 'lat': round(lat, 2), 'lon': round(lon, 2)})
gl.sort(key=lambda x: x['id'])
aq = ('https://erddap.ifremer.fr/erddap/tabledap/ArgoFloats.json?platform_number,time,latitude,longitude&time%3E=now-' + str(ARGO_DAYS) +
      'days&orderByMax(%22platform_number,time%22)')
ar = []
for wmo, t, lat, lon in rows(get(aq)):
    if lat is None or lon is None: continue
    ar.append([str(wmo), round(lat, 2), round(lon, 2), str(t)[:10]])
ar.sort(key=lambda x: x[0])
stamp = now.strftime('%Y-%m-%dT%H:%M:%SZ')
out = {
 'about': 'Snapshot of active uncrewed deployments for the map layer on map.html. Generated by tools/refresh_uncrewed_deployments.py. Positions are the latest reported, rounded to 0.01 degrees. Not a navigation aid.',
 'generated': stamp,
 'gliders': {'source': 'IOOS Glider Data Assembly Center (NOAA IOOS), ERDDAP', 'url': 'https://gliders.ioos.us/', 'as_of': stamp, 'window_days': GLIDER_DAYS, 'items': gl},
 'argo': {'source': 'Argo Program (Ifremer Argo ERDDAP)', 'url': 'https://argo.ucsd.edu/', 'as_of': stamp, 'window_days': ARGO_DAYS,
          'fields': ['wmo', 'lat', 'lon', 'last_profile_date'], 'items': ar},
}
(ROOT / 'data/uncrewed_deployments.json').write_text(json.dumps(out, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8')
js = json.dumps(out, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')
(ROOT / 'data/uncrewed_deployments.js').write_text('/* Generated from data/uncrewed_deployments.json by tools/refresh_uncrewed_deployments.py. Do not edit. */\nwindow.RV_DEPLOYMENTS=' + js + ';\n', encoding='utf-8')
print(f'gliders {len(gl)}  argo floats {len(ar)}  as of {stamp}')
